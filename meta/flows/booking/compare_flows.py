"""Three-way Meta Flow comparison: published baseline vs any number of variants.

Machine-readable. Every claim in the R1 closeout about a published-to-target delta is
generated by this file, so prose and artifact cannot disagree.
"""
import hashlib, json, sys


def load(p):
    raw = open(p, "rb").read()
    return json.loads(raw), hashlib.sha256(raw).hexdigest()


def walk(node, out, path="layout"):
    """Every component, in document order, with its bindings."""
    if isinstance(node, dict):
        t = node.get("type")
        if t:
            out.append({
                "path": path,
                "type": t,
                "name": node.get("name"),
                "label": node.get("label"),
                "text": node.get("text"),
                "visible": node.get("visible"),
                "enabled": node.get("enabled"),
                "required": node.get("required"),
                "data-source": node.get("data-source"),
                "init-value": node.get("init-value"),
                "action": _action(node),
            })
        for k, v in node.items():
            if k in ("children",):
                walk(v, out, path + "/" + k)
    elif isinstance(node, list):
        for i, v in enumerate(node):
            walk(v, out, "%s[%d]" % (path, i))
    return out


def _action(node):
    a = node.get("on-click-action") or node.get("on-select-action")
    if not a:
        return None
    return {
        "name": a.get("name"),
        "next": (a.get("next") or {}).get("name"),
        "payload": dict(sorted((a.get("payload") or {}).items())),
    }


def bindings(screen):
    """${data.X} actually rendered by a component, vs declared but bound nowhere."""
    blob = json.dumps(screen.get("layout", {}), ensure_ascii=False)
    decl = set(screen.get("data", {}))
    rendered, carried = set(), set()
    for k in decl:
        (rendered if ("${data.%s}" % k) in blob else carried).add(k)
    return rendered, carried


def nav_payloads(screen):
    """Actions keyed by the OWNING COMPONENT's identity, not by its path.

    Inserting a component shifts the array indices of everything after it, so a
    path-keyed map reports every later action as changed. That would have overstated the
    published-to-target delta: the two refusal TextBody components move the Form from
    `children[3]` to `children[5]`, and the Dropdown and Footer actions underneath it are
    byte-identical. Identity is type + name + label, which is stable across insertions and
    still distinguishes the two actions on one screen.
    """
    out = {}
    for c in walk(screen.get("layout", {}), []):
        if c["action"]:
            key = "%s:%s:%s" % (c["type"], c["name"] or "-", c["label"] or "-")
            out[key] = c["action"]
    return out


def describe(doc):
    per = {}
    for s in doc["screens"]:
        rendered, carried = bindings(s)
        decl = s.get("data", {})
        per[s["id"]] = {
            "terminal": bool(s.get("terminal")),
            "declared": {k: decl[k].get("type") for k in sorted(decl)},
            "rendered": sorted(rendered),
            "carried": sorted(carried),
            "components": [
                {k: v for k, v in c.items() if v is not None} for c in walk(s.get("layout", {}), [])
            ],
            "visibility": {c["path"]: c["visible"]
                           for c in walk(s.get("layout", {}), []) if c.get("visible")},
            "actions": nav_payloads(s),
        }
    return {"version": doc.get("version"), "data_api_version": doc.get("data_api_version"),
            "routing_model": doc.get("routing_model"), "screens": per}


def delta(base, var):
    d = {"routing_model": {}, "screens": {}}
    if base["routing_model"] != var["routing_model"]:
        for k in sorted(set(base["routing_model"]) | set(var["routing_model"])):
            b, v = base["routing_model"].get(k), var["routing_model"].get(k)
            if b != v:
                d["routing_model"][k] = {"published": b, "variant": v}
    for sid in sorted(set(base["screens"]) | set(var["screens"])):
        b, v = base["screens"].get(sid), var["screens"].get(sid)
        if b is None:
            d["screens"][sid] = {"screen": "ADDED"}
            continue
        if v is None:
            d["screens"][sid] = {"screen": "REMOVED"}
            continue
        e = {}
        bd, vd = set(b["declared"]), set(v["declared"])
        if vd - bd:
            e["fields_added"] = sorted(vd - bd)
        if bd - vd:
            e["fields_removed"] = sorted(bd - vd)
        ch = {k: {"published": b["declared"][k], "variant": v["declared"][k]}
              for k in sorted(bd & vd) if b["declared"][k] != v["declared"][k]}
        if ch:
            e["fields_type_changed"] = ch
        # compared by CONTENT, not by position: inserting a component shifts the paths of
        # everything after it, and reporting those as rewritten would overstate the delta.
        def _body(c):
            return json.dumps({k: x for k, x in c.items() if k != "path"},
                              sort_keys=True, ensure_ascii=False)
        bc = [_body(c) for c in b["components"]]
        vc = [_body(c) for c in v["components"]]
        if bc != vc:
            added, removed = list(vc), list(bc)
            for x in list(added):
                if x in removed:
                    removed.remove(x)
                    added.remove(x)
            if added:
                e["components_added"] = [json.loads(x) for x in added]
            if removed:
                e["components_removed"] = [json.loads(x) for x in removed]
            if not added and not removed:
                e["components_reordered_only"] = True
        if b["visibility"] != v["visibility"]:
            e["visibility_changed"] = {"published": b["visibility"], "variant": v["visibility"]}
        if b["actions"] != v["actions"]:
            e["actions_changed"] = {"published": b["actions"], "variant": v["actions"]}
        if b["terminal"] != v["terminal"]:
            e["terminal_changed"] = {"published": b["terminal"], "variant": v["terminal"]}
        # classification of the variant's own fields
        e["classification"] = {
            **{k: "RENDERED" for k in v["rendered"]},
            **{k: "CARRIED (declared, bound nowhere)" for k in v["carried"]},
        }
        if e:
            d["screens"][sid] = e
    return d


if __name__ == "__main__":
    base_p, variants = sys.argv[1], sys.argv[2:]
    base_doc, base_sha = load(base_p)
    base = describe(base_doc)
    report = {"published": {"path": base_p, "sha256": base_sha, "model": base}, "variants": []}
    for p in variants:
        doc, sha = load(p)
        v = describe(doc)
        report["variants"].append({"path": p, "sha256": sha, "model": v,
                                   "delta_from_published": delta(base, v)})
    print(json.dumps(report, indent=1, ensure_ascii=False))
